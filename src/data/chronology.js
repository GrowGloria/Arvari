/**
 * Мини-лента для тизера на главной: начало цикла, середина и «ныне».
 * Строится из самой хронологии, чтобы блоки не разъезжались при её правке.
 */
export function chronologyTeaser(epochs) {
  if (!epochs?.length) return [];
  const first = epochs[0]?.events?.[0];
  const middle = epochs[Math.floor(epochs.length / 2)]?.events?.[0];
  const items = [];
  if (first) items.push({ year: first.year, text: first.title, style: 'solid', dot: '#7a3b26' });
  if (middle) items.push({ year: middle.year, text: middle.title, style: 'solid', dot: '#b4894c' });
  items.push({ year: 'Ныне', text: 'Начало игры', style: 'dashed', dot: '#3a2414' });
  return items;
}

